//! MV2X 10-subband audio decoder used by CVNS for BGM, SE, and voice streams.

// Format and tables reference: cvns.exe SHA-256 8e6044466b928d77f0a94a0d0f32fe48190596bf628115598881c2aa3a4885aa,
// sub_478990..sub_479080 and tables at 0x4A4A58, 0x4A4E58, 0x4A5258 (base 0x400000).
use crate::{FormatError, MAX_PAYLOAD, pb3::u16_at, pb3::u32_at};
use std::sync::Arc;

pub const HEADER_SIZE: usize = 18;
const SAMPLES_PER_FRAME: usize = 320;
const BANDS: usize = 10;
const BAND_SAMPLES: usize = 32;

/// Parsed 18-byte MV2X audio stream header.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Header {
    pub samples_per_channel: u32,
    pub field08: u16,
    pub sample_rate: u16,
    pub channels: u8,
    pub shift_param: u8,
    pub frame_count: u32,
}

impl Header {
    /// Parses and validates an MV2X header against research bounds.
    pub fn parse(raw: &[u8]) -> Result<Self, FormatError> {
        if raw.len() < HEADER_SIZE || raw.len() > MAX_PAYLOAD || raw.get(..4) != Some(b"MV2X") {
            return Err(FormatError("expected bounded MV2X audio header"));
        }
        let h = Self {
            samples_per_channel: u32_at(raw, 4)?,
            field08: u16_at(raw, 8)?,
            sample_rate: u16_at(raw, 10)?,
            channels: raw[12],
            shift_param: raw[13],
            frame_count: u32_at(raw, 14)?,
        };
        if !(1..=2).contains(&h.channels) {
            return Err(FormatError("MV2X supports 1 or 2 channels"));
        }
        if !(8000..=192_000).contains(&u32::from(h.sample_rate)) {
            return Err(FormatError("MV2X sample rate out of range"));
        }
        if h.shift_param > 6 {
            return Err(FormatError("MV2X output shift parameter exceeds 6"));
        }
        let max_samples = u64::from(h.frame_count) * (SAMPLES_PER_FRAME as u64);
        if u64::from(h.samples_per_channel) > max_samples {
            return Err(FormatError("MV2X sample count exceeds frame count"));
        }
        if u64::from(h.samples_per_channel) * u64::from(h.channels) * 2 > MAX_PAYLOAD as u64 {
            return Err(FormatError("MV2X decoded PCM exceeds research bounds"));
        }
        Ok(h)
    }
}

/// Streaming frame-by-frame MV2X decoder producing interleaved signed 16-bit PCM.
pub struct Decoder {
    bytes: Arc<[u8]>,
    header: Header,
    cursor: usize,
    bit_buf: u32,
    bits_left: u8,
    frame_index: u32,
    rings: Vec<[i32; 1024]>,
    ring_pos: Vec<usize>,
}

impl Decoder {
    /// Creates a streaming MV2X decoder over shared archive bytes.
    pub fn new(bytes: Arc<[u8]>) -> Result<Self, FormatError> {
        let header = Header::parse(&bytes)?;
        let channels = usize::from(header.channels);
        Ok(Self {
            bytes,
            header,
            cursor: HEADER_SIZE,
            bit_buf: 0,
            bits_left: 0,
            frame_index: 0,
            rings: vec![[0i32; 1024]; channels],
            ring_pos: vec![0usize; channels],
        })
    }

    pub fn header(&self) -> &Header {
        &self.header
    }

    /// Decodes the next frame (up to 320 interleaved sample frames), or `None` at EOF.
    pub fn next_frame(&mut self) -> Result<Option<Vec<i16>>, FormatError> {
        if self.frame_index >= self.header.frame_count {
            return Ok(None);
        }
        let channels = usize::from(self.header.channels);
        let mut channel_pcm = vec![[0i32; SAMPLES_PER_FRAME]; channels];
        for (c, out) in channel_pcm.iter_mut().enumerate() {
            let active = self.read_bits(10)? as usize;
            let quant_index = self.read_bits(9)? as usize;
            if active > SAMPLES_PER_FRAME {
                return Err(FormatError("MV2X subband coefficient count exceeds frame"));
            }
            let scale = *QUANT_SCALE
                .get(quant_index)
                .ok_or(FormatError("MV2X quantizer index out of bounds"))?;
            let mut coeffs = [0i32; SAMPLES_PER_FRAME];
            let mut idx = 0;
            while idx < active {
                let bits = self.read_unary()?;
                if bits != 0 {
                    let raw = self.read_bits(bits)? as i32;
                    let half = 1i32 << (bits - 1);
                    let signed = if raw < half {
                        raw - (1i32 << bits) + 1
                    } else {
                        raw
                    };
                    coeffs[idx] = scale.wrapping_mul(signed);
                    idx += 1;
                } else {
                    let skip = self.read_bits(3)? as usize;
                    idx += skip + 1;
                }
            }
            for band in 0..BANDS {
                synth_band(
                    &coeffs[band * BAND_SAMPLES..(band + 1) * BAND_SAMPLES],
                    &mut self.rings[c],
                    &mut self.ring_pos[c],
                    &mut out[band * BAND_SAMPLES..(band + 1) * BAND_SAMPLES],
                );
            }
        }
        let produced = self.frame_index * (SAMPLES_PER_FRAME as u32);
        let take = self
            .header
            .samples_per_channel
            .saturating_sub(produced)
            .min(SAMPLES_PER_FRAME as u32) as usize;
        self.frame_index += 1;

        let shift = 6 - self.header.shift_param;
        let mut interleaved = Vec::with_capacity(take * channels);
        for s in 0..take {
            for ch in &channel_pcm {
                let sample = (ch[s] >> shift).clamp(-32767, 32767) as i16;
                interleaved.push(sample);
            }
        }
        Ok(Some(interleaved))
    }

    fn next_bit(&mut self) -> Result<u32, FormatError> {
        if self.bits_left == 0 {
            if self.cursor >= self.bytes.len() {
                return Err(FormatError("truncated MV2X bitstream"));
            }
            let avail = (self.bytes.len() - self.cursor).min(4);
            let mut buf = [0u8; 4];
            buf[..avail].copy_from_slice(&self.bytes[self.cursor..self.cursor + avail]);
            self.cursor += avail;
            self.bit_buf = u32::from_le_bytes(buf);
            self.bits_left = 32;
        }
        let bit = self.bit_buf & 1;
        self.bit_buf >>= 1;
        self.bits_left -= 1;
        Ok(bit)
    }

    fn read_bits(&mut self, count: u8) -> Result<u32, FormatError> {
        let mut value = 0u32;
        for _ in 0..count {
            value = (value << 1) | self.next_bit()?;
        }
        Ok(value)
    }

    fn read_unary(&mut self) -> Result<u8, FormatError> {
        let mut count = 0u8;
        while self.next_bit()? != 0 {
            count += 1;
            if count > 30 {
                return Err(FormatError("MV2X Huffman unary prefix exceeds 30 bits"));
            }
        }
        Ok(count)
    }
}

/// Decodes a complete MV2X buffer into `(header, interleaved_i16_pcm)`.
pub fn decode(bytes: Arc<[u8]>) -> Result<(Header, Vec<i16>), FormatError> {
    let mut decoder = Decoder::new(bytes)?;
    let header = decoder.header().clone();
    let total = (header.samples_per_channel as usize) * usize::from(header.channels);
    let mut pcm = Vec::with_capacity(total);
    while let Some(frame) = decoder.next_frame()? {
        pcm.extend_from_slice(&frame);
    }
    Ok((header, pcm))
}

fn synth_band(coeffs: &[i32], ring: &mut [i32; 1024], ring_pos: &mut usize, out: &mut [i32]) {
    let pos = *ring_pos;
    for row in 0..64 {
        let base = row * BAND_SAMPLES;
        let mut sum = 0i32;
        for k in 0..BAND_SAMPLES {
            let term = coeffs[k].wrapping_mul(i32::from(IMDCT_MATRIX[base + k])) >> 10;
            sum = sum.wrapping_add(term);
        }
        ring[(pos + row) & 0x3ff] = sum;
    }
    for s in 0..BAND_SAMPLES {
        let mut acc = 0i32;
        for k in 0..16 {
            let ring_off = ((k & !1) * 64) + ((k & 1) * 96);
            let sample = ring[(pos + s + ring_off) & 0x3ff];
            let coeff = i32::from(SYNTH_WINDOW[k * 32 + s]);
            let term = sample.wrapping_mul(coeff) >> 10;
            if (k & 2) == 0 {
                acc = acc.wrapping_add(term);
            } else {
                acc = acc.wrapping_sub(term);
            }
        }
        out[s] = acc;
    }
    *ring_pos = pos.wrapping_sub(64) & 0x3ff;
}

