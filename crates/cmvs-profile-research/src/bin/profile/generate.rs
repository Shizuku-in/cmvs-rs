use cmvs_core::{
    format::digest::to_hex,
    profile::{RecordFile, Registry},
};
use std::{
    fmt::{self, Write},
    fs::{self, OpenOptions},
    io::{self, Write as _},
    path::Path,
};

pub(super) fn replace_table(path: &Path, data: &[u8]) -> io::Result<()> {
    let mut staging_name = path
        .file_name()
        .ok_or_else(|| io::Error::new(io::ErrorKind::InvalidInput, "output needs a file name"))?
        .to_os_string();
    staging_name.push(format!(".{}.tmp", std::process::id()));
    let staging = path.with_file_name(staging_name);
    let mut file = OpenOptions::new()
        .write(true)
        .create_new(true)
        .open(&staging)?;
    let written = file.write_all(data).and_then(|()| file.sync_all());
    drop(file);
    let result = written.and_then(|()| fs::rename(&staging, path));
    if result.is_err() {
        let _ = fs::remove_file(&staging);
    }
    result
}

fn file(out: &mut impl Write, path: &str, sha256: &[u8; 32]) -> fmt::Result {
    write!(out, "file({path:?}, \"{}\")", to_hex(sha256))
}

fn files(out: &mut impl Write, records: &[RecordFile]) -> fmt::Result {
    writeln!(out, "&[")?;
    for record in records {
        write!(out, "            ")?;
        file(out, &record.path, &record.sha256)?;
        writeln!(out, ",")?;
    }
    write!(out, "        ]")
}

pub(super) fn write_playback(out: &mut impl Write, registry: &Registry) -> fmt::Result {
    writeln!(out, "// Generated by cmvs-profile generate-playback.")?;
    writeln!(
        out,
        "use super::{{BinaryData, GameData, ProfileData, file, statuses}};"
    )?;
    writeln!(
        out,
        "use crate::{{\n    exe::Arch,\n    profile::{{Family, VariantId}},\n}};"
    )?;
    writeln!(out)?;
    writeln!(out, "#[rustfmt::skip]")?;
    writeln!(out, "pub(super) static PROFILES: &[ProfileData] = &[")?;
    for profile in registry.profiles() {
        writeln!(out, "    ProfileData {{")?;
        writeln!(out, "        id: {:?},", profile.id)?;
        writeln!(out, "        family: Family::{:?},", profile.family)?;
        writeln!(out, "        base: {:?},", profile.base)?;
        writeln!(out, "        binaries: &[")?;
        for binary in &profile.binaries {
            write!(out, "            BinaryData(Arch::{:?}, ", binary.arch)?;
            file(out, &binary.file, &binary.sha256)?;
            writeln!(out, "),")?;
        }
        writeln!(out, "        ],")?;
        writeln!(out, "        statuses: &statuses(b\"\\")?;
        let codes: Vec<_> = profile
            .statuses()
            .iter()
            .map(|status| status.name().as_bytes()[0])
            .collect();
        for line in codes.chunks(72) {
            writeln!(
                out,
                "            {}\\",
                std::str::from_utf8(line).expect("ASCII status codes")
            )?;
        }
        writeln!(out, "        \"),")?;
        if !profile.variants().is_empty() {
            writeln!(out, "        variants: &[")?;
            for (command, variant) in profile.variants() {
                writeln!(
                    out,
                    "            (0x{command:03x}, VariantId::{:?}),",
                    variant
                )?;
            }
            writeln!(out, "        ],")?;
        } else {
            writeln!(out, "        variants: &[],")?;
        }
        if profile.is_cvns() {
            writeln!(out, "        maps: &[")?;
            for command in 0..profile.statuses().len() as u16 {
                if let Some(target) = profile.map(command) {
                    writeln!(out, "            (0x{command:03x}, 0x{target:03x}),")?;
                }
            }
            writeln!(out, "        ],")?;
        } else {
            writeln!(out, "        maps: &[],")?;
        }
        writeln!(out, "    }},")?;
    }
    writeln!(out, "];")?;
    writeln!(out)?;
    writeln!(out, "#[rustfmt::skip]")?;
    writeln!(out, "pub(super) static GAMES: &[GameData] = &[")?;
    for game in registry.games() {
        writeln!(out, "    GameData {{")?;
        writeln!(out, "        game: {:?},", game.game)?;
        writeln!(out, "        profile: {:?},", game.profile)?;
        write!(out, "        start_scripts: ")?;
        files(out, &game.start_scripts)?;
        writeln!(out, ",")?;
        write!(out, "        script_archive: ")?;
        file(out, &game.script_archive.path, &game.script_archive.sha256)?;
        writeln!(out, ",")?;
        writeln!(out, "        game_id: 0x{:08x},", game.game_id)?;
        write!(out, "        executables: ")?;
        files(out, &game.executables)?;
        writeln!(out, ",")?;
        writeln!(
            out,
            "        skip_auto_resume: {:?},",
            game.skip_auto_resume
        )?;
        writeln!(out, "    }},")?;
    }
    writeln!(out, "];")
}
